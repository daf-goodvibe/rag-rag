// Helper to generate dynamic, realistic candlestick series for any timeframe
export function generateCandles(basePrice: number, timeframe: string, count = 40): MarketAssetCandleSeries {
  const candles: { time: string; timestamp: number; open: number; high: number; low: number; close: number; volume: number }[] = [];
  const now = Date.now();
  
  let stepMs = 5 * 60 * 1000; // 5 min default for 1D
  if (timeframe === '5D') stepMs = 30 * 60 * 1000;
  if (timeframe === '1M') stepMs = 4 * 60 * 60 * 1000;
  if (timeframe === '3M') stepMs = 24 * 60 * 60 * 1000;
  if (timeframe === '6M') stepMs = 48 * 60 * 60 * 1000;
  if (timeframe === '1Y') stepMs = 7 * 24 * 60 * 60 * 1000;
  if (timeframe === '5Y' || timeframe === 'ALL') stepMs = 30 * 24 * 60 * 60 * 1000;

  let currentPrice = basePrice * 0.95;
  const volatility = basePrice * 0.012;

  for (let i = count; i >= 0; i--) {
    const timeStamp = now - i * stepMs;
    const dateObj = new Date(timeStamp);
    
    let timeStr = dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    if (timeframe !== '1D' && timeframe !== '5D') {
      timeStr = dateObj.toLocaleDateString([], { month: 'short', day: 'numeric' });
    }

    const delta = (Math.random() - 0.48) * volatility;
    const open = currentPrice;
    const close = Math.max(1, open + delta);
    const high = Math.max(open, close) + Math.random() * (volatility * 0.6);
    const low = Math.min(open, close) - Math.random() * (volatility * 0.6);
    const volume = Math.floor(Math.random() * 500000 + 100000);

    candles.push({
      time: timeStr,
      timestamp: timeStamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Ensure last close matches current asset price
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return { candles };
}

export interface MarketAssetCandleSeries {
  candles: {
    time: string;
    timestamp: number;
    open: number;
    high: number;
    low: number;
    close: number;
    volume: number;
  }[];
}
